// Padankan nama tanpa mengira huruf besar/kecil, apostrof dan ruang berlebihan.
export const normalizeName = (name: string) => name.toUpperCase().replace(/[’'`]/g, "").replace(/\s+/g, " ").trim();

// Kunci longgar: abaikan BIN/BINTI/B./BT., samakan MUHAMMAD/MOHAMMAD/MOHD/MUHD/MOHAMAD, abaikan tertib perkataan.
// Digunakan untuk padanan import dan pengesanan nama berulang.
const LOOSE_ALIAS: Record<string, string> = { MOHAMMAD: "MUHAMMAD", MOHD: "MUHAMMAD", MUHD: "MUHAMMAD", MOHAMAD: "MUHAMMAD", MUHAMAD: "MUHAMMAD", MOHAMED: "MUHAMMAD", MD: "MUHAMMAD" };
const LOOSE_SKIP = new Set(["BIN", "BINTI", "B", "BT", "BTE", "BINTE", "A/L", "A/P", "AL", "AP"]);
export const looseNameTokens = (name: string) =>
  normalizeName(name).replace(/[.\-/]/g, " ").split(" ").filter(w => w && !LOOSE_SKIP.has(w)).map(w => LOOSE_ALIAS[w] || w).sort();
export const looseNameKey = (name: string) => looseNameTokens(name).join(" ");
